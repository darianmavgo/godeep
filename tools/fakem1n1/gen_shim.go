//go:build ignore

// gen_shim assembles shim.asm with Apple clang and writes shim_code.go.
// Run with `go generate ./tools/fakem1n1` (macOS with Xcode command-line tools).
package main

import (
	"bytes"
	"debug/macho"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
)

func main() {
	dir, err := os.MkdirTemp("", "fakem1n1-shim")
	check(err)
	defer os.RemoveAll(dir)
	obj := filepath.Join(dir, "shim.o")
	cmd := exec.Command("clang", "-c", "-x", "assembler", "-arch", "arm64", "shim.asm", "-o", obj)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	check(cmd.Run())

	f, err := macho.Open(obj)
	check(err)
	sec := f.Section("__text")
	if sec == nil {
		check(fmt.Errorf("no __text in %s", obj))
	}
	if len(sec.Relocs) != 0 {
		check(fmt.Errorf("shim.asm must assemble without relocations (has %d)", len(sec.Relocs)))
	}
	code, err := sec.Data()
	check(err)
	if len(code)%8 != 0 {
		check(fmt.Errorf("shim is %d bytes, want a multiple of 8", len(code)))
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_shim.go from shim.asm; DO NOT EDIT.\n\npackage main\n\n")
	b.WriteString("var shimCode = []byte{")
	for i, c := range code {
		if i%16 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "0x%02x,", c)
	}
	b.WriteString("\n}\n")
	check(os.WriteFile("shim_code.go", b.Bytes(), 0o644))
	fmt.Printf("shim_code.go: %d bytes\n", len(code))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen_shim:", err)
		os.Exit(1)
	}
}
